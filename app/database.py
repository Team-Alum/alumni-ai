def get_analytics_summary() -> Dict[str, Any]:
    with get_connection() as conn:
        cursor = conn.cursor()

        _exec(cursor, "SELECT COUNT(*) AS total_queries, COALESCE(AVG(latency_ms), 0) AS avg_latency FROM analytics_events")
        totals = cursor.fetchone()
        total_queries = totals["total_queries"] if totals else 0
        avg_latency = round(float(totals["avg_latency"] or 0), 1)

        _exec(cursor, "SELECT COUNT(*) AS c FROM users")
        total_users = cursor.fetchone()["c"]

        _exec(cursor, "SELECT COUNT(*) AS c FROM sessions")
        total_sessions = cursor.fetchone()["c"]

        today = datetime.utcnow().strftime("%Y-%m-%d")
        _exec(cursor, "SELECT COUNT(*) AS c FROM analytics_events WHERE substr(created_at, 1, 10) = %s", (today,))
        queries_today = cursor.fetchone()["c"]

        week_cutoff = (datetime.utcnow() - timedelta(days=7)).isoformat()
        _exec(cursor, "SELECT COUNT(DISTINCT user_id) AS c FROM analytics_events WHERE created_at >= %s", (week_cutoff,))
        active_users_7d = cursor.fetchone()["c"]

        _exec(cursor, """
            SELECT provider_used, COUNT(*) as count 
            FROM analytics_events 
            GROUP BY provider_used 
            ORDER BY count DESC
        """)
        providers = {r["provider_used"]: r["count"] for r in cursor.fetchall()}

        _exec(cursor, """
            SELECT mode, COUNT(*) as count 
            FROM analytics_events 
            GROUP BY mode 
            ORDER BY count DESC
        """)
        modes = {r["mode"]: r["count"] for r in cursor.fetchall()}

        _exec(cursor, """
            SELECT status, COUNT(*) as count 
            FROM analytics_events 
            GROUP BY status
        """)
        statuses = {r["status"]: r["count"] for r in cursor.fetchall()}

        _exec(cursor, """
            SELECT substr(created_at, 1, 10) as day, COUNT(*) as count
            FROM analytics_events
            GROUP BY day
            ORDER BY day DESC
            LIMIT 7
        """)
        daily = [{"day": r["day"], "count": r["count"]} for r in cursor.fetchall()]

        return {
            "total_queries": total_queries,
            "total_users": total_users,
            "total_sessions": total_sessions,
            "queries_today": queries_today,
            "active_users_7d": active_users_7d,
            "avg_latency_ms": avg_latency,
            "provider_distribution": providers,
            "mode_distribution": modes,
            "status_distribution": statuses,
            "daily_volume": daily
        }

