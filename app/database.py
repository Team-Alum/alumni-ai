def save_message(session_id: str, sender: str, content: str, mode: str = "professional", attachments: Optional[str] = None) -> Dict[str, Any]:
    now = datetime.utcnow().isoformat()
    with get_connection() as conn:
        cursor = conn.cursor()
        _exec(cursor,
            "INSERT INTO messages (session_id, sender, content, mode, attachments, created_at) VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
            (session_id, sender, content, mode, attachments, now)
        )
        msg_row = cursor.fetchone()
        msg_id = msg_row["id"] if msg_row else None
        _exec(cursor, "UPDATE sessions SET updated_at = %s WHERE id = %s", (now, session_id))
        conn.commit()

    parsed_att = None
    if attachments:
        try:
            import json
            parsed_att = json.loads(attachments)
        except Exception:
            pass

    return {
        "id": msg_id,
        "session_id": session_id,
        "sender": sender,
        "content": content,
        "mode": mode,
        "attachments": parsed_att,
        "created_at": now
    }

def get_messages_by_session(session_id: str) -> List[Dict[str, Any]]:
    with get_connection() as conn:
        cursor = conn.cursor()
        _exec(cursor, "SELECT * FROM messages WHERE session_id = %s ORDER BY id ASC", (session_id,))
        rows = cursor.fetchall()
        result = []
        for r in rows:
            d = dict(r)
            if "attachments" in d and d["attachments"]:
                try:
                    import json
                    d["attachments"] = json.loads(d["attachments"])
                except Exception:
                    pass
            result.append(d)
        return result

MEMORY_MAX_PER_USER = 60

def get_user_memories(user_id: str) -> List[Dict[str, Any]]:
    with get_connection() as conn:
        cursor = conn.cursor()
        _exec(cursor, "SELECT id, content, source, created_at FROM user_memories WHERE user_id = %s ORDER BY id ASC", (user_id,))
