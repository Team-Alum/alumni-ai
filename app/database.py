def get_user_by_email(email: str) -> Optional[Dict[str, Any]]:
    if not email:
        return None
    with get_connection() as conn:
        cursor = conn.cursor()
        _exec(cursor, "SELECT * FROM users WHERE LOWER(email) = LOWER(%s)", (email.strip(),))
        row = cursor.fetchone()
        return dict(row) if row else None

