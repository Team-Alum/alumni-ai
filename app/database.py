_IS_PG = DATABASE_URL.startswith(("postgres://", "postgresql://"))

# Password hashing is intentionally versioned so old hashes can be verified and
# transparently upgraded on the next successful login.
_PBKDF2_ALGORITHM = "pbkdf2_sha256"
_PBKDF2_ITERATIONS = 260_000
_LEGACY_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
AUTH_TOKEN_TTL_DAYS = 90


@contextmanager
def get_connection():
    if _IS_PG:
        import psycopg
        from psycopg.rows import dict_row
        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15)
        try:
            yield conn
            conn.commit()
        finally:
            conn.close()
    else:
        conn = sqlite3.connect(DB_PATH)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA synchronous=NORMAL;")
        conn.execute("PRAGMA foreign_keys=ON;")
        try:
            yield conn
            conn.commit()
        finally:
            conn.close()


def _exec(cursor, sql: str, params: tuple = ()):
    if not _IS_PG:
        sql = sql.replace("%s", "?")
    cursor.execute(sql, params)
    return cursor


def _pg_schema_ready(cursor) -> bool:
    """One fast round-trip instead of 14 DDL round-trips on every cold start."""
    _exec(cursor, """
        SELECT
            to_regclass('public.users') IS NOT NULL
            AND to_regclass('public.auth_tokens') IS NOT NULL
            AND to_regclass('public.sessions') IS NOT NULL
            AND to_regclass('public.messages') IS NOT NULL
            AND to_regclass('public.analytics_events') IS NOT NULL
            AND to_regclass('public.user_memories') IS NOT NULL
            AND to_regclass('public.visitor_events') IS NOT NULL
            AND to_regclass('public.account_removals') IS NOT NULL
            AND EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'idx_analytics_created')
            AND EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'idx_analytics_user')
            AND EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'idx_analytics_provider')
            AND EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'idx_sessions_user')
            AND EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'idx_messages_session')
            AND EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'idx_memories_user')
            AND EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'idx_visitor_created')
            AS ready
    """)
    row = cursor.fetchone()
    if not row:
        return False
    if isinstance(row, dict):
        return bool(row.get("ready"))
    return bool(row[0])


def init_db():
    pk_auto = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if _IS_PG else "INTEGER PRIMARY KEY AUTOINCREMENT"
    with get_connection() as conn:
        cursor = conn.cursor()
        if _IS_PG and _pg_schema_ready(cursor):
            return

        _exec(cursor, """
            CREATE TABLE IF NOT EXISTS users (
                id TEXT PRIMARY KEY,
                username TEXT NOT NULL,
                email TEXT NOT NULL,
                login_method TEXT NOT NULL,
                is_team_alum INTEGER DEFAULT 0,
                created_at TEXT NOT NULL,
                password_hash TEXT
            );
        """)
        _exec(cursor, """
            CREATE TABLE IF NOT EXISTS auth_tokens (
                token TEXT PRIMARY KEY,
                user_id TEXT NOT NULL,
                created_at TEXT NOT NULL,
                FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
            );
        """)
        _exec(cursor, """
            CREATE TABLE IF NOT EXISTS sessions (
                id TEXT PRIMARY KEY,
                user_id TEXT NOT NULL,
                title TEXT NOT NULL,
                category TEXT DEFAULT 'general',
                mode TEXT DEFAULT 'professional',
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
            );
        """)
        _exec(cursor, f"""
            CREATE TABLE IF NOT EXISTS messages (
                id {pk_auto},
                session_id TEXT NOT NULL,
                sender TEXT NOT NULL,
                content TEXT NOT NULL,
                mode TEXT DEFAULT 'professional',
                attachments TEXT,
                created_at TEXT NOT NULL,
                FOREIGN KEY (session_id) REFERENCES sessions (id) ON DELETE CASCADE
            );
        """)
        _exec(cursor, f"""
            CREATE TABLE IF NOT EXISTS analytics_events (
                id {pk_auto},
                user_id TEXT NOT NULL,
                session_id TEXT,
                prompt_chars INTEGER NOT NULL,
                response_chars INTEGER NOT NULL,
                latency_ms INTEGER NOT NULL,
                provider_used TEXT NOT NULL,
                fallback_count INTEGER DEFAULT 0,
                mode TEXT NOT NULL,
                status TEXT NOT NULL,
                created_at TEXT NOT NULL,
                FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
            );
        """)

        _exec(cursor, f"""
            CREATE TABLE IF NOT EXISTS user_memories (
                id {pk_auto},
                user_id TEXT NOT NULL,
                content TEXT NOT NULL,
                source TEXT DEFAULT 'manual',
                created_at TEXT NOT NULL,
                FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
            );
        """)
        _exec(cursor, f"""
            CREATE TABLE IF NOT EXISTS visitor_events (
                id {pk_auto},
                visitor_key TEXT NOT NULL,
                path TEXT DEFAULT '/',
                created_at TEXT NOT NULL
            );
        """)
        # Removing access is a soft removal: the user row, sessions, messages
        # and analytics history stay intact, while this table records the
        # warning and blocks every authenticated endpoint except /auth/me.
        _exec(cursor, """
            CREATE TABLE IF NOT EXISTS account_removals (
                user_id TEXT PRIMARY KEY,
                reason TEXT DEFAULT 'suspicious_username',
                warning TEXT NOT NULL,
                removed_by TEXT,
                removed_at TEXT NOT NULL,
                username_snapshot TEXT,
                email_snapshot TEXT,
                FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
            );
        """)

        _exec(cursor, "CREATE INDEX IF NOT EXISTS idx_analytics_created ON analytics_events(created_at);")
        _exec(cursor, "CREATE INDEX IF NOT EXISTS idx_analytics_user ON analytics_events(user_id);")
        _exec(cursor, "CREATE INDEX IF NOT EXISTS idx_analytics_provider ON analytics_events(provider_used);")
        _exec(cursor, "CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);")
        _exec(cursor, "CREATE INDEX IF NOT EXISTS idx_messages_session ON messages(session_id);")
        _exec(cursor, "CREATE INDEX IF NOT EXISTS idx_memories_user ON user_memories(user_id);")
        _exec(cursor, "CREATE INDEX IF NOT EXISTS idx_visitor_created ON visitor_events(created_at);")
        conn.commit()


def hash_password(password: str) -> str:
    """PBKDF2-HMAC-SHA256 with a per-user random salt."""
    if not password:
        raise ValueError("password must not be empty")
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac(
        "sha256", password.encode("utf-8"), salt, _PBKDF2_ITERATIONS
    )
    return (
        f"{_PBKDF2_ALGORITHM}${_PBKDF2_ITERATIONS}"
        f"${salt.hex()}${digest.hex()}"
    )


def verify_password(stored_hash: Optional[str], provided_password: Optional[str]) -> bool:
    """Verify current hashes and the legacy unsalted SHA-256 format.

    A missing stored hash is *not* a valid password. Callers must explicitly
    handle passwordless (Google/guest) accounts.
    """
    if not stored_hash or not provided_password:
        return False

    stored = str(stored_hash).strip()
    try:
        if stored.startswith(f"{_PBKDF2_ALGORITHM}$"):
            _, iterations, salt_hex, digest_hex = stored.split("$", 3)
            digest = hashlib.pbkdf2_hmac(
                "sha256",
                provided_password.encode("utf-8"),
                bytes.fromhex(salt_hex),
                int(iterations),
            )
            return hmac.compare_digest(digest.hex(), digest_hex)
        if _LEGACY_SHA256_RE.match(stored):
            legacy = hashlib.sha256(provided_password.encode("utf-8")).hexdigest()
            return hmac.compare_digest(legacy, stored)
    except (TypeError, ValueError):
        return False
    return False


def password_needs_rehash(stored_hash: Optional[str]) -> bool:
    return bool(stored_hash) and not str(stored_hash).startswith(f"{_PBKDF2_ALGORITHM}$")


def save_user(
    user_id: str,
    username: str,
    email: str,
    login_method: str,
    is_team_alum: bool,
    password: Optional[str] = None,
    clear_password: bool = False,
) -> Dict[str, Any]:
    with get_connection() as conn:
        cursor = conn.cursor()
        _exec(cursor, "SELECT * FROM users WHERE id = %s", (user_id,))
        existing = cursor.fetchone()
        now = datetime.utcnow().isoformat()
        pwd_hash = hash_password(password) if password else None

        if existing:
            if pwd_hash:
                _exec(cursor,
                    "UPDATE users SET username = %s, email = %s, login_method = %s, is_team_alum = %s, password_hash = %s WHERE id = %s",
                    (username, email, login_method, 1 if is_team_alum else 0, pwd_hash, user_id)
                )
            elif clear_password:
                _exec(cursor,
                    "UPDATE users SET username = %s, email = %s, login_method = %s, is_team_alum = %s, password_hash = NULL WHERE id = %s",
                    (username, email, login_method, 1 if is_team_alum else 0, user_id)
                )
            else:
                _exec(cursor,
                    "UPDATE users SET username = %s, email = %s, login_method = %s, is_team_alum = %s WHERE id = %s",
                    (username, email, login_method, 1 if is_team_alum else 0, user_id)
                )
        else:
            _exec(cursor,
                "INSERT INTO users (id, username, email, login_method, is_team_alum, created_at, password_hash) VALUES (%s, %s, %s, %s, %s, %s, %s)",
                (user_id, username, email, login_method, 1 if is_team_alum else 0, now, pwd_hash)
            )
        conn.commit()
        return {
            "id": user_id,
            "username": username,
            "email": email,
            "login_method": login_method,
            "is_team_alum": is_team_alum
        }

